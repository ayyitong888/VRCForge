import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { build } from "esbuild";

const require = createRequire(import.meta.url);
async function bundle(options) {
  const result = await build({ ...options, bundle: true, write: false, platform: "node", format: "cjs", external: ["react"] });
  const module = { exports: {} };
  new Function("require", "module", "exports", result.outputFiles[0].text)(require, module, module.exports);
  return module.exports;
}
const current = await bundle({ entryPoints: ["src/hooks/use-runtime-turn-continuation.ts"] });
const activity = await bundle({ entryPoints: ["src/hooks/use-runtime-turn-activity.ts"] });
const streaming = await bundle({ entryPoints: ["src/lib/chat-streaming.ts"] });
const identity = { sessionId: "session", clientTurnId: "client", turnId: "turn" };
const event = { ...identity, continuationSource: "foreground_completed", plan: { nextStep: "needs_user_action" } };
const externalRow = { id: "runtime-activity:client", type: "streaming", clientTurnId: "client", text: "" };
assert.equal(current.runtimeContinuationDeliveryState(event, [externalRow]), "append", "fixed external activity settles from the authoritative receipt");
assert.equal(current.runtimeContinuationDeliveryState(event, [{ ...externalRow, id: "stream-client" }]), "defer", "the local sender still owns its HTTP completion");
const run = { ...identity, status: "running" };
const chat = { id: "chat", sessionId: "session", projectPath: "", title: "", items: [] };
const projected = activity.projectRuntimeTurnActivity(chat, run);
const older = { ...run, turnId: "old", startedAt: "2026-10-23T12:00:00Z", updatedAt: "2026-10-23T12:03:00Z" };
const newer = { ...run, turnId: "new", startedAt: "2026-10-23T12:01:00Z", updatedAt: "2026-10-23T12:02:00Z" };
assert.equal(activity.runtimeActivityCancelTarget([chat], chat, [older, newer]).turnId, "new",
  "Stop owns the newest start even if the older run updated last");
assert.equal(activity.runtimeActivityCancelTarget([chat], chat, [older, { ...newer, status: "completed" }]), undefined,
  "a stale active row cannot revive a superseded generation");
assert.equal(projected.items.length, 1);
assert.equal(activity.projectRuntimeTurnActivity(projected, run), projected, "repeated discovery does not create another stream");
assert.equal(activity.projectRuntimeTurnActivity(chat, { ...run, status: "failed" }), chat, "a terminal snapshot cannot resurrect activity");
const owned = { ...chat, items: [{ ...externalRow, id: "stream-client" }] };
assert.equal(activity.projectRuntimeTurnActivity(owned, run), owned, "another lifecycle's streaming row is retained");
assert.equal(activity.runtimeActivityOwner([chat, { ...chat, id: "ambiguous" }], identity), undefined);
assert.equal(activity.runtimeActivityOwner([chat, { ...chat, id: "exact", items: [{ id: "u", type: "user", clientTurnId: "client" }] }], identity).id, "exact");
assert.equal(activity.runtimeActivityOwner([{ ...chat, sessionId: "wrong" }], identity), undefined);
const response = { ...identity, session_id: "session", turn_id: "turn", ok: true, observe: {}, plan: { nextStep: "needs_user_action", summary: "User decision required" } };
const state = { ...identity, ok: true, status: "completed", response };
assert.equal(activity.runtimeEventFromExactResponse({ ...state, status: "running" }, identity), undefined);
assert.equal(activity.runtimeEventFromExactResponse({ ...state, clientTurnId: "wrong" }, identity), undefined);
assert.equal(activity.runtimeEventFromExactResponse({ ...state, response: { ...response, turnId: "wrong" } }, identity), undefined);
const recovered = activity.runtimeEventFromExactResponse(state, identity);
assert.equal(recovered.plan.nextStep, "needs_user_action");
assert.equal(recovered.completedAt, undefined);
const withoutAlias = { ...response, clientTurnId: undefined };
assert.equal(activity.runtimeEventFromExactResponse({ ...state, response: withoutAlias }, identity).clientTurnId, identity.clientTurnId);
assert.equal(activity.runtimeEventFromExactResponse({ ...state, response: withoutAlias }, { ...identity, turnId: undefined }), undefined, "missing aliases require the exact run's authoritative backend turn");
const publicEvent = { id: "public-0", sequence: 0, timestamp: "2026-10-23T12:00:00Z", kind: "assistant", payload: { phase: "commentary", summary: "原始公开对话".repeat(3000) } };
assert.equal(streaming.normalizeAgentRuntimeTimelineEvent(publicEvent).payload.summary, publicEvent.payload.summary, "the shared reader retains complete accepted assistant bodies within the backend bound");
assert.equal(streaming.normalizeAgentRuntimeTimelineEvent({ ...publicEvent, kind: "tool_result" }).payload.summary.length, 1000);
const delta = { ...identity, type: "agentRuntimeDelta", timelineEvent: publicEvent };
const once = activity.applyRuntimeActivityDelta(projected, delta);
const twice = activity.applyRuntimeActivityDelta(once, delta);
assert.equal(twice.items[0].timeline.length, 1, "readback/live overlap deduplicates by occurrence id");
assert.equal(twice.items[0].timeline[0].payload.summary, publicEvent.payload.summary);
assert.equal(activity.applyRuntimeActivityDelta(projected, { ...delta, sessionId: "wrong" }), projected);
const settled = { ...chat, items: [{ id: "runtime-reply-client", type: "agent", response }] };
const filled = activity.applyRuntimeActivityDelta(settled, delta);
assert.equal(filled.items[0].timeline.length, 1, "a final-before-history race backfills the receipt rather than reopening activity");
assert.equal(filled.items[0].response.plan.nextStep, "needs_user_action");
const filledLegacy = activity.applyRuntimeActivityDelta({ ...chat, items: [{ id: "legacy", type: "agent", response: withoutAlias }] }, delta);
assert.equal(filledLegacy.items[0].timeline.length, 1, "an exact backend turn also restores a reply without CID");
console.log("runtime activity regression: generation selection, ownership, local lifecycle, terminal status, body retention, event dedupe");
